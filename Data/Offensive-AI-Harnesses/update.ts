// Refreshes this dataset from the Offsec Harness Index (offsecharnesses.ai), its source of record.
// Usage: bun Data/Offensive-AI-Harnesses/update.ts [--from <url-or-path>]   (default https://offsecharnesses.ai/data.json)
// Writes harnesses.json (verbatim), harnesses.csv, sources.csv and SUMMARY.md, and appends a line to update.log. No API key.
import { appendFileSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIR = import.meta.dir;
const i = process.argv.indexOf("--from");
const from = i > 0 ? process.argv[i + 1]! : "https://offsecharnesses.ai/data.json";
const raw = from.startsWith("https://") ? await (await fetch(from)).text() : readFileSync(from, "utf8");

interface Use { tag: string; basis: string; source: string; quote?: string }
interface Harness { name: string; table: string; tier: string; repo: string | null; description: string; kind?: string; stars: number | null; license?: string | null; last_push?: string; actors?: { name: string }[]; what_it_did?: string; breach?: string; uses: Use[]; sources?: string[] }
interface Source { id: string; publisher: string; kind: string; date: string; title: string; url: string }
const d = JSON.parse(raw) as { evidence_reviewed: string; github_facts: string; use_tags: { key: string; label: string; def: string }[]; harnesses: Harness[]; sources: Source[] };
if (!Array.isArray(d.harnesses) || d.harnesses.length === 0 || !Array.isArray(d.sources)) throw new Error(`no harnesses in ${from}`);
for (const h of d.harnesses) for (const u of h.uses) if (!u.source.startsWith("https://")) throw new Error(`${h.name}: use tag ${u.tag} has no https source`);

const csv = (rows: (string | number | null | undefined)[][]): string => rows.map((r) => r.map((v) => { const s = v == null ? "" : String(v).replace(/<[^>]+>/g, ""); return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s; }).join(",")).join("\n") + "\n";
const tags = (h: Harness, basis: string) => h.uses.filter((u) => u.basis === basis).map((u) => u.tag).join(" ");
writeFileSync(join(DIR, "harnesses.json"), raw.endsWith("\n") ? raw : raw + "\n");
writeFileSync(join(DIR, "harnesses.csv"), csv([
  ["name", "table", "tier", "repo", "kind", "stars", "license", "last_push", "uses_seen_in_attacks", "uses_from_readme", "actors", "breach", "source_ids", "description"],
  ...d.harnesses.map((h) => [h.name, h.table, h.tier, h.repo, h.kind ?? "", h.stars, h.license ?? "", h.last_push ?? "", tags(h, "attack report"), tags(h, "project docs"), (h.actors ?? []).map((a) => a.name).join("; "), h.breach ?? "", (h.sources ?? []).join(" "), h.what_it_did ?? h.description]),
]));
writeFileSync(join(DIR, "sources.csv"), csv([["id", "date", "publisher", "kind", "title", "url"], ...d.sources.map((s) => [s.id, s.date, s.publisher, s.kind, s.title, s.url])]));

const ev = d.harnesses.filter((h) => h.table === "evidence");
const confirmed = ev.filter((h) => h.tier === "confirmed").length;
const all = d.harnesses.map((h) => h.uses.map((u) => u.tag));
const scanOnly = all.filter((t) => t.length && t.every((x) => x === "recon" || x === "scan")).length;
const count = (k: string) => all.filter((t) => t.includes(k)).length;
const pubs = new Set(d.sources.map((s) => s.publisher.split(" · ")[0])).size;
const today = new Date().toISOString().slice(0, 10);
writeFileSync(join(DIR, "SUMMARY.md"), `# Offensive AI Harnesses: Executive Summary

> Generated by \`update.ts\` from https://offsecharnesses.ai/data.json on ${today}. Do not edit by hand.

## 🎯 BEST ESTIMATE

| Metric | Value | Confidence | Last Updated |
|--------|-------|------------|--------------|
| **Open-source offensive AI harnesses tracked** | **${d.harnesses.length}** | 80% (roster is a floor: public GitHub, 100+ stars) | ${d.github_facts} |
| **Seen in real attacks (primary reporting)** | **${ev.length}** (${confirmed} confirmed, ${ev.length - confirmed} observed) | 90% (floor: only what a report names) | ${d.evidence_reviewed} |
| **Claim no more than recon or scanning** | **${scanOnly}** of ${d.harnesses.length} | 75% (each project's own README, untested) | ${d.github_facts} |
| **Primary reports behind the evidence** | **${d.sources.length}** from ${pubs} publishers | 95% | ${d.evidence_reviewed} |

**One-liner:** ${ev.length} of ${d.harnesses.length} open-source offensive AI harnesses have documented attacker use.

**Caveat:** A harness with no attack on record has none in primary reporting, which does not mean none happened.

---

## Use tags (harnesses carrying each)

| Tag | Harnesses | Meaning |
|-----|-----------|---------|
${d.use_tags.map((t) => `| ${t.label} | ${count(t.key)} | ${t.def} |`).join("\n")}

## Seen in real attacks

| Harness | Tier | Used for in attacks | Breach |
|---------|------|---------------------|--------|
${ev.map((h) => `| ${h.name} | ${h.tier} | ${tags(h, "attack report").split(" ").filter(Boolean).map((k) => d.use_tags.find((t) => t.key === k)!.label).join(", ") || "—"} | ${h.breach ?? ""} |`).join("\n")}

Full rows: [harnesses.csv](./harnesses.csv) · sources: [sources.csv](./sources.csv) · method: [source.md](./source.md) · research: [research/offensive-ai-harnesses-2026-11](../../research/offensive-ai-harnesses-2026-11/README.md)
`);
appendFileSync(join(DIR, "update.log"), `${new Date().toISOString()} from=${from.startsWith("https://") ? from : "local file"} harnesses=${d.harnesses.length} evidence=${ev.length} sources=${d.sources.length} evidence_reviewed=${d.evidence_reviewed} github_facts=${d.github_facts}\n`);
console.log(`✓ ${d.harnesses.length} harnesses, ${d.sources.length} sources written from ${from}`);

// Keep this dataset's row in Data/README.md in step with the data, so the index of datasets never shows stale counts.
const README = join(DIR, "..", "README.md");
const readme = readFileSync(README, "utf8");
const row = /^\| \[Offensive AI Harnesses\]\(\.\/Offensive-AI-Harnesses\/SUMMARY\.md\) \| [^|]* \|/m;
if (!row.test(readme)) throw new Error("Data/README.md has no Offensive AI Harnesses row to update");
writeFileSync(README, readme.replace(row, `| [Offensive AI Harnesses](./Offensive-AI-Harnesses/SUMMARY.md) | ${ev.length} of ${d.harnesses.length} seen in real attacks |`));
